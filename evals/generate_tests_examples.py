#!/usr/bin/env python3
"""Regenerate evals/tests.examples.generated.yaml from the bundled example
task logs (the curated, hand-labelled fixtures — see generate_tests.py for
the suite that grades your system's own real logs instead).

The expected *verdict* for each log is imported directly from
backend/test_eval_engine.py::EXPECTED_EXAMPLE_VERDICTS — the exact table
the pytest suite cross-checks against — so this promptfoo suite can never
silently drift from the unit tests it mirrors. The expected *reason*
keyword (used to confirm the right check fired, not just that some check
failed) is maintained here, next to the log contents it describes.

Run this again whenever a file is added, removed, or renamed under
logs/eval_examples/, or whenever EXPECTED_EXAMPLE_VERDICTS changes:

    python3 evals/generate_tests_examples.py
"""
from __future__ import annotations

import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BASE_DIR)

from backend.test_eval_engine import EXPECTED_EXAMPLE_VERDICTS  # noqa: E402

EXAMPLES_DIR = os.path.join(BASE_DIR, "logs", "eval_examples")
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests.examples.generated.yaml")

# Substring expected somewhere in EvalReport.reasons for non-PASS examples —
# confirms the *right* check fired, not just that *some* check failed.
# Keep these loosely worded (see the actual messages in
# backend/eval_engine.py) so small copy tweaks there don't break the suite.
REASON_KEYWORDS = {
    "task_101_battery_depleted.json": "battery",
    "task_102_robot_stuck.json": "stuck",
    "task_103_path_not_found.json": "route",
    "task_104_collision_detected.json": "collision",
    "task_105_box_already_reserved.json": "already reserved",
    "task_106_controller_error.json": "controller error",
    "task_107_task_cancelled.json": "cancelled",
    "task_108_battery_low_recovered.json": "battery",
    "task_110_entities_invalid_firmware.json": "unapproved firmware",
    "task_112_mixed_mission_uncertified_operator.json": "electrical_safety",
    "task_115_mid_task_authorization_changed.json": "authorization changed mid-task",
    "task_116_dual_signoff_second_signer_uncertified.json": "second signer",
    "task_117_false_success_box_never_arrived.json": "doesn't match a real delivery",
    "task_118_batch_deliver_false_success.json": "doesn't match a real delivery",
}

HEADER = """\
# AUTO-GENERATED by evals/generate_tests_examples.py — do not hand-edit.
# Ground truth: backend/test_eval_engine.py::EXPECTED_EXAMPLE_VERDICTS
# Regenerate with: python3 evals/generate_tests_examples.py
"""


def _yaml_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def build_tests() -> str:
    lines = [HEADER.rstrip(), ""]
    for filename, verdict in sorted(EXPECTED_EXAMPLE_VERDICTS.items()):
        rel_path = f"logs/eval_examples/{filename}"
        lines.append(f'- description: "{filename} should grade as {verdict.value}"')
        lines.append("  vars:")
        lines.append(f'    task_log: "{_yaml_escape(rel_path)}"')
        lines.append(f'    expected_verdict: "{verdict.value}"')
        keyword = REASON_KEYWORDS.get(filename)
        if keyword:
            lines.append(f'    expected_reason_contains: "{_yaml_escape(keyword)}"')
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    if not os.path.isdir(EXAMPLES_DIR):
        print(f"No such directory: {EXAMPLES_DIR}", file=sys.stderr)
        return 1

    on_disk = {
        f for f in os.listdir(EXAMPLES_DIR)
        if f.startswith("task_") and f.endswith(".json")
    }
    missing = on_disk - set(EXPECTED_EXAMPLE_VERDICTS)
    if missing:
        print(
            "warning: these example logs have no expected verdict in "
            f"EXPECTED_EXAMPLE_VERDICTS and were skipped: {sorted(missing)}",
            file=sys.stderr,
        )
    stale = set(EXPECTED_EXAMPLE_VERDICTS) - on_disk
    if stale:
        print(
            "warning: EXPECTED_EXAMPLE_VERDICTS references files that no "
            f"longer exist on disk: {sorted(stale)}",
            file=sys.stderr,
        )

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write(build_tests())
    print(f"Wrote {len(EXPECTED_EXAMPLE_VERDICTS)} test case(s) to {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
