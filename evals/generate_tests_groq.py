#!/usr/bin/env python3
"""Regenerate evals/tests.groq.generated.yaml from the REAL task logs your
system has actually produced — logs/tasks/task_*.json — one promptfoo test
case per log.

Each test carries FOUR pieces of evidence as vars, mirroring how a person
would actually check a task — what was asked for, who/what was involved,
what changed, and the full story:

  task_json         the task AS CREATED — type, requested robot, box,
                     source/destination, priority (from TASK_CREATED;
                     see TaskManager.create_task's data=). What was asked
                     for, not what happened.
  entities_json      identity only — which robot, which box, which zones
                     this task involves (ids, names, zone keys/labels).
                     No state here on purpose; see state_diff_json for
                     that.
  state_diff_json    the world-state snapshot captured right before the
                     task ran and right after it hit a terminal event —
                     robot/box position+status, source/destination zone
                     occupancy (see TaskManager.snapshot_state). The
                     PRIMARY thing the model is asked to judge: did the
                     box actually end up where the task intended, not
                     just "did some event fire".
  task_log_json      the trimmed event list — supporting context for
                     *why*, and the only evidence at all for logs
                     recorded before state snapshots existed.

task_json and entities_json degrade gracefully (a "note" explaining what
couldn't be resolved) rather than erroring, same as state_diff_json,
since older logs won't carry the newer fields either.

Run after your system has performed one or more tasks, whenever you want
a fresh Groq-graded report over what actually happened:

    python3 evals/generate_tests_groq.py
    npx promptfoo eval -c evals/promptfooconfig.groq.yaml --env-file evals/.env -j 1
"""
from __future__ import annotations

import glob
import json
import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGS_DIR = os.path.join(BASE_DIR, "logs", "tasks")
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests.groq.generated.yaml")

HEADER = """\
# AUTO-GENERATED by evals/generate_tests_groq.py — do not hand-edit.
# Source: every logs/tasks/task_*.json your system has actually produced.
# Regenerate after running new tasks with: python3 evals/generate_tests_groq.py
"""


def _indent_block(text: str, spaces: int) -> str:
    """Indent every non-blank line of a YAML block-literal scalar's body."""
    pad = " " * spaces
    return "\n".join(pad + line if line else line for line in text.splitlines())


def discover_real_logs() -> list[str]:
    return sorted(glob.glob(os.path.join(LOGS_DIR, "task_*.json")))


# extract_task/extract_entities/extract_state_diff used to be duplicated
# here; they now live in backend/eval_engine.py (the "Mission Authorization
# Record" functions) as the single source of truth, since
# check_entities_valid and check_state_transition grade exactly this same
# evidence deterministically. Reusing them here guarantees the LLM and the
# rule-based engine are always looking at identical data.
sys.path.insert(0, BASE_DIR)
from backend.eval_engine import extract_entities, extract_state_diff, extract_task  # noqa: E402


# backend/eval_engine.py's checks only ever read seq, event, task_id,
# robot_id and message off a record (grep the module for `e.get(` /
# `e[...]` and that's the complete list) — timestamp, time, level,
# category, position and data never factor into a verdict. Dropping them
# for the LLM prompt loses no signal our own rule-based grader uses
# either, and roughly halves the JSON's size on top of the event filter.
_KEPT_FIELDS = ("seq", "event", "task_id", "robot_id", "box_id", "message")
_EXTRA_FIELDS = ("repeat_count", "note")  # added by _collapse_repeats, if present


def _slim(event: dict) -> dict:
    out = {k: event[k] for k in _KEPT_FIELDS if k in event}
    out.update({k: event[k] for k in _EXTRA_FIELDS if k in event})
    return out


def _collapse_repeats(events: list[dict]) -> list[dict]:
    """Collapse consecutive runs of an identical (event, message) pair into
    one representative record carrying a repeat_count — e.g. 24 identical
    ROBOT_WAITING records (the robot yielding to traffic tick after tick)
    become a single entry annotated "repeated 24 times". This is the other
    big source of oversized prompts: a long stuck/deadlock episode is
    exactly the same named event over and over, which is expensive to spell
    out in full but trivial to summarize without losing the signal (the
    engine's own check just counts them — see check_stuck_or_deadlock)."""
    collapsed = []
    i = 0
    n = len(events)
    while i < n:
        e = events[i]
        j = i + 1
        while (
            j < n
            and events[j].get("event") == e.get("event")
            and events[j].get("message") == e.get("message")
        ):
            j += 1
        run_len = j - i
        if run_len > 1:
            rep = dict(e)
            rep["repeat_count"] = run_len
            rep["note"] = (
                f"this event repeated {run_len} times consecutively "
                f"(seq {e.get('seq')}-{events[j - 1].get('seq')})"
            )
            collapsed.append(rep)
        else:
            collapsed.append(e)
        i = j
    return collapsed


def build_tests(files: list[str]) -> str:
    lines = [HEADER.rstrip(), ""]
    for f in files:
        rel_path = os.path.relpath(f, BASE_DIR)
        name = os.path.basename(f)
        with open(f, "r", encoding="utf-8") as fh:
            events = json.load(fh)
        # Keep only the named, structured events (TASK_CREATED,
        # BATTERY_LOW, COLLISION_DETECTED, ...) — the same ones
        # backend/eval_engine.py's own checks key off (see _by_event()).
        # Raw per-tick "moved from (x,y) to (x2,y2)" DEBUG records carry no
        # decision-relevant signal and were most of every log's size —
        # dropping them cuts prompt tokens by roughly 70% and is what
        # actually keeps requests under Groq's per-minute token limit.
        meaningful = _collapse_repeats([e for e in events if e.get("event")])
        slimmed = [_slim(e) for e in meaningful]

        task_def = extract_task(events)
        state_diff = extract_state_diff(events)
        entities = extract_entities(task_def, state_diff)

        task_pretty = json.dumps(task_def, indent=2, ensure_ascii=False)
        entities_pretty = json.dumps(entities, indent=2, ensure_ascii=False)
        state_pretty = json.dumps(state_diff, indent=2, ensure_ascii=False)
        log_pretty = json.dumps(slimmed, indent=2, ensure_ascii=False)

        lines.append(f'- description: "{name} (real log) — Groq judges the state transition"')
        lines.append("  vars:")
        lines.append(f'    task_log: "{rel_path}"')
        # Block literal (|) needs no quoting/escaping, so the raw JSON —
        # full of quotes and braces — can go in as-is.
        lines.append("    task_json: |")
        lines.append(_indent_block(task_pretty, 6))
        lines.append("    entities_json: |")
        lines.append(_indent_block(entities_pretty, 6))
        lines.append("    state_diff_json: |")
        lines.append(_indent_block(state_pretty, 6))
        lines.append("    task_log_json: |")
        lines.append(_indent_block(log_pretty, 6))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    if not os.path.isdir(LOGS_DIR):
        print(f"No such directory: {LOGS_DIR}", file=sys.stderr)
        return 1

    files = discover_real_logs()
    if not files:
        print(
            f"No task_*.json files found in {LOGS_DIR} yet — run some tasks "
            "through the digital twin first, then regenerate. Leaving "
            f"{OUT_PATH} untouched.",
            file=sys.stderr,
        )
        return 2

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write(build_tests(files))
    print(f"Wrote {len(files)} test case(s) to {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
