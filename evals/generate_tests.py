#!/usr/bin/env python3
"""Regenerate evals/tests.generated.yaml from the REAL task logs your
system has actually produced — logs/tasks/task_*.json — one promptfoo test
case per log. There's no pre-known "correct" verdict for a live run (see
generate_tests_examples.py for the curated fixture suite that does have
one); the assertion (shared/asserts/no_regressions.py) just requires each
log to grade out healthy — PASS or WARN, never FAIL.

Run this after your system has performed one or more tasks, whenever you
want a fresh promptfoo report over what actually happened:

    python3 evals/generate_tests.py
    npx promptfoo eval -c evals/promptfooconfig.yaml
"""
from __future__ import annotations

import glob
import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGS_DIR = os.path.join(BASE_DIR, "logs", "tasks")
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests.generated.yaml")

HEADER = """\
# AUTO-GENERATED by evals/generate_tests.py — do not hand-edit.
# Source: every logs/tasks/task_*.json your system has actually produced.
# Regenerate after running new tasks with: python3 evals/generate_tests.py
"""


def _yaml_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def discover_real_logs() -> list[str]:
    return sorted(glob.glob(os.path.join(LOGS_DIR, "task_*.json")))


def build_tests(files: list[str]) -> str:
    lines = [HEADER.rstrip(), ""]
    for f in files:
        rel_path = os.path.relpath(f, BASE_DIR)
        name = os.path.basename(f)
        lines.append(f'- description: "{name} (real log) should grade out healthy"')
        lines.append("  vars:")
        lines.append(f'    task_log: "{_yaml_escape(rel_path)}"')
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    if not os.path.isdir(LOGS_DIR):
        print(f"No such directory: {LOGS_DIR}", file=sys.stderr)
        return 1

    files = discover_real_logs()
    if not files:
        print(
            f"No task_*.json files found in {LOGS_DIR} yet — run some tasks "
            "through the digital twin first, then regenerate. Leaving "
            f"{OUT_PATH} untouched.",
            file=sys.stderr,
        )
        return 2

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write(build_tests(files))
    print(f"Wrote {len(files)} test case(s) to {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
